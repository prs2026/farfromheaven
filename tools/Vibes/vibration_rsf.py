"""Versioned Rocket Simulation File (RSF): JSON settings and CSV references only."""

from __future__ import annotations

import argparse
import json
import os
from datetime import datetime, timezone
from pathlib import Path

if __package__:
    from . import preliminary_vibration
else:
    import preliminary_vibration


SCHEMA = "projectblaze-vibration-rsf"
VERSION = 1
CSV_FIELDS = ("trajectory", "hr", "lr", "motor_curve", "transfer", "motor_psd")
SETTING_DEFAULTS = {
    "end_time": "", "provenance": "measured", "latitude": "", "longitude": "",
    "local_time": "", "timezone": "America/Los_Angeles", "mode": "auto",
    "elevation": "", "length": "", "station": "", "motor_mass": "",
    "avionics_mass": "", "damping": "", "exhaust_velocity": "",
    "ignition_time": "0", "ref_thrust": "", "ref_ve": "", "ref_mass": "",
    "cq": "0.02", "frequency_max": "2000", "output_dir": "vibration_runs",
}
# These model arguments are supplied by the form or generated by the workflow.
FORM_MODEL_FIELDS = {
    "trajectory", "output_dir", "trajectory_provenance", "vehicle_length_m",
    "station_from_nose_m", "motor_mass_kg", "avionics_mass_kg",
    "structural_damping_ratio", "cq", "frequency_max_hz", "motor_psd",
    "transfer_function", "reference_thrust_n", "reference_exhaust_velocity_mps",
    "reference_motor_mass_kg",
}


def model_options(overrides: dict | None = None) -> dict:
    """Capture and validate all model options not represented by the basic form."""
    actions = {a.dest: a for a in preliminary_vibration.parser()._actions
               if a.dest not in FORM_MODEL_FIELDS | {"help"}}
    overrides = {} if overrides is None else overrides
    if not isinstance(overrides, dict) or overrides.keys() - actions.keys():
        raise ValueError("RSF contains unknown model options")
    result = {key: action.default for key, action in actions.items()}
    for key, value in overrides.items():
        action = actions[key]
        if value is None:
            if action.default is not None:
                raise ValueError(f"Model option {key} cannot be null")
            result[key] = None
            continue
        if isinstance(value, (bool, dict, list)):
            raise ValueError(f"Invalid value for model option {key}")
        try:
            parsed = action.type(str(value)) if action.type else value
        except (ValueError, TypeError, argparse.ArgumentTypeError) as exc:
            raise ValueError(f"Invalid model option {key}: {value}") from exc
        if action.choices and parsed not in action.choices:
            raise ValueError(f"Invalid choice for model option {key}: {value}")
        result[key] = str(parsed) if isinstance(parsed, Path) else parsed
    return result


def resolve_csv_paths(values: dict[str, str]) -> dict[str, str]:
    """Relative CSV names refer to the selected inputs folder, never the CWD."""
    resolved = dict(values)
    folder = Path(values.get("csv_inputs_folder") or ".").expanduser().resolve()
    for key in CSV_FIELDS:
        if values.get(key):
            path = Path(values[key]).expanduser()
            resolved[key] = str((path if path.is_absolute() else folder / path).resolve())
    return resolved


def resolve_model_options(options: dict | None, values: dict[str, str]) -> dict:
    result = model_options(options)
    if result["motor_tones"]:
        path = Path(result["motor_tones"]).expanduser()
        folder = Path(values.get("csv_inputs_folder") or ".").expanduser()
        result["motor_tones"] = str((path if path.is_absolute() else folder / path).resolve())
    return result


def _relative(path: Path, folder: Path) -> str:
    """Use a relative reference where possible, retaining Windows cross-drive paths."""
    try:
        return Path(os.path.relpath(path, folder)).as_posix()
    except ValueError:
        return str(path)


def save_rsf(values: dict[str, str], output: Path, *, options: dict | None = None,
             overwrite: bool = False) -> Path:
    """Save a draft or complete setup; no CSV is copied, moved, or embedded."""
    output = output.expanduser().resolve()
    if output.suffix.lower() != ".rsf":
        raise ValueError("Simulation files must end in .RSF")
    unknown = values.keys() - (SETTING_DEFAULTS.keys() | set(CSV_FIELDS) | {"csv_inputs_folder"})
    if unknown or any(not isinstance(value, str) for value in values.values()):
        raise ValueError("Unknown or non-string simulation settings")
    folder = Path(values.get("csv_inputs_folder") or ".").expanduser().resolve()
    resolved = resolve_csv_paths(values)
    settings = {key: values.get(key, default) for key, default in SETTING_DEFAULTS.items()}
    if settings["output_dir"]:
        settings["output_dir"] = _relative(Path(settings["output_dir"]).expanduser().resolve(), output.parent)
    extras = resolve_model_options(options, values)
    if extras["motor_tones"]:
        extras["motor_tones"] = _relative(Path(extras["motor_tones"]), folder)
    document = {
        "schema": SCHEMA, "version": VERSION,
        "saved_at_utc": datetime.now(timezone.utc).isoformat(),
        "csv_inputs_folder": _relative(folder, output.parent),
        "csv_files": {key: _relative(Path(resolved[key]), folder) if resolved.get(key) else ""
                      for key in CSV_FIELDS},
        "settings": settings,
        "model_options": extras,
    }
    content = json.dumps(document, indent=2, ensure_ascii=False, allow_nan=False) + "\n"
    output.parent.mkdir(parents=True, exist_ok=True)
    # Exclusive creation prevents accidental replacement unless explicitly approved.
    with output.open("w" if overwrite else "x", encoding="utf-8") as stream:
        stream.write(content)
    return output


def load_rsf(source: Path) -> tuple[dict[str, str], dict, list[str]]:
    """Validate completely before returning settings for the GUI to apply."""
    source = source.expanduser().resolve()
    document = json.loads(source.read_text(encoding="utf-8-sig"))
    if not isinstance(document, dict) or document.get("schema") != SCHEMA:
        raise ValueError("Not a Project Blaze vibration RSF file")
    if type(document.get("version")) is not int or document["version"] != VERSION:
        raise ValueError(f"Unsupported RSF version: {document.get('version')!r}")
    settings, files = document.get("settings"), document.get("csv_files")
    for section, expected, name in ((settings, set(SETTING_DEFAULTS), "settings"),
                                    (files, set(CSV_FIELDS), "csv_files")):
        if not isinstance(section, dict) or set(section) != expected:
            raise ValueError(f"RSF {name} has missing or unknown fields")
        if any(not isinstance(value, str) for value in section.values()):
            raise ValueError(f"RSF {name} values must be strings (blank for unset)")
    folder = document.get("csv_inputs_folder")
    if not isinstance(folder, str) or not folder:
        raise ValueError("RSF csv_inputs_folder must be a nonempty path")
    extra = document.get("model_options")
    if not isinstance(extra, dict) or set(extra) != set(model_options()):
        raise ValueError("RSF model_options has missing or unknown fields")
    extra = model_options(extra)
    values = {**settings, **files}
    folder_path = Path(folder).expanduser()
    values["csv_inputs_folder"] = str((source.parent / folder_path).resolve())
    if values["output_dir"]:
        values["output_dir"] = str((source.parent / Path(values["output_dir"]).expanduser()).resolve())
    resolved = resolve_csv_paths(values)
    warnings = [f"Missing {key} CSV: {resolved[key]}" for key in CSV_FIELDS
                if resolved[key] and not Path(resolved[key]).is_file()]
    tones = resolve_model_options(extra, values)["motor_tones"]
    if tones and not Path(tones).is_file():
        warnings.append(f"Missing motor tones CSV: {tones}")
    return values, extra, warnings
